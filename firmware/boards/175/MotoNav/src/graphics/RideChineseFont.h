static inline void drawRideCnGlyph(RideCnGlyph g, int x, int y, uint16_t color) {
  if ((int)g < 0 || g >= RIDE_CN_COUNT) return;
  for (int yy=0; yy<16; yy++) { uint16_t bits = ((uint16_t)pgm_read_byte(&RIDE_CN_BITMAPS[g][yy*2]) << 8) | pgm_read_byte(&RIDE_CN_BITMAPS[g][yy*2+1]); for (int xx=0; xx<16; xx++) if (bits & (1u << (15-xx))) gfx->drawPixel(x+xx, y+yy, color); }
}
static inline void drawRideCnText(const RideCnGlyph *glyphs, int count, int cx, int y, uint16_t color, int gap=0) { int w=count*16+(count>0?(count-1)*gap:0); int x=cx-w/2; for(int i=0;i<count;i++){ drawRideCnGlyph(glyphs[i],x,y,color); x+=16+gap; } }
